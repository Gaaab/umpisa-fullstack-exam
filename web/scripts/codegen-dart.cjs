// graphql-codegen plugin: emits each operation as a Dart const string for the
// Flutter client, with the fragments it uses appended so it runs standalone.
const { Kind, print, visit } = require("graphql");

function plugin(_schema, documents) {
  const definitions = documents.flatMap((d) => d.document.definitions);
  const fragments = new Map(
    definitions
      .filter((d) => d.kind === Kind.FRAGMENT_DEFINITION)
      .map((f) => [f.name.value, f]),
  );

  const usedFragments = (node, used = new Set()) => {
    visit(node, {
      FragmentSpread({ name }) {
        if (used.has(name.value)) return;
        used.add(name.value);
        usedFragments(fragments.get(name.value), used);
      },
    });
    return used;
  };

  const constants = definitions
    .filter((d) => d.kind === Kind.OPERATION_DEFINITION)
    .map((operation) => {
      const name = operation.name.value;
      const constName =
        name[0].toLowerCase() + name.slice(1) + operation.operation[0].toUpperCase() + operation.operation.slice(1);
      const text = [operation, ...[...usedFragments(operation)].map((f) => fragments.get(f))]
        .map((node) => print(node))
        .join("\n\n");
      return `const ${constName} = r'''\n${text}\n''';`;
    });

  return [
    "// GENERATED by `pnpm codegen` in web/ from graphql/operations. Do not edit.",
    ...constants,
  ].join("\n\n") + "\n";
}

module.exports = { plugin };
